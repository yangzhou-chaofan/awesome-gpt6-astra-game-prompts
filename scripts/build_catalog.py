"""Regenerate CATALOG.md and site/index.html from the catalog entries.

    python3 scripts/build_catalog.py            # rewrite CATALOG.md and site/index.html
    python3 scripts/build_catalog.py --check    # exit 1 if either is stale (CI)

Both outputs are generated, so they can never silently disagree with the entries
on disk. Run scripts/validate_catalog.py first (this script does it for you and
aborts on errors).
"""

