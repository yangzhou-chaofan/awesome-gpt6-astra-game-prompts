CATALOG_MD = ROOT / "CATALOG.md"
SITE = ROOT / "site" / "index.html"
REPO_URL = "https://github.com/yangzhou-chaofan/awesome-gpt6-astra-game-prompts"

SECTION_RE = re.compile(r"^## (.+?)\s*$\n+(.*?)(?=\n## |\Z)", re.MULTILINE | re.DOTALL)


def read_sections(path: Path) -> dict[str, str]:
    body = path.read_text(encoding="utf-8")
    body = body.split("---", 2)[-1]  # drop frontmatter
    out: dict[str, str] = {}
    for name, text in SECTION_RE.findall(body):
        out[name.strip()] = " ".join(text.split())
    return out


def load() -> list[dict]:
    entries = []
    for path, meta in iter_entries():
        if "__error__" in meta:
            continue
        sections = read_sections(path)
        rel = path.relative_to(ROOT).as_posix()
        entries.append(
            {
                "id": meta["id"],
                "title": meta["title"],
                "category": meta["category"],
                "kind": meta["kind"],
                "tier": meta["tier"],
                "source_platform": meta["source_platform"],
                "source_url": meta["source_url"],
                "author": meta["author"],
                "has_prompt": bool(meta["has_prompt"]),
                "prompt_note": meta.get("prompt_note", ""),
                "stars": meta.get("stars"),
                "signals": meta.get("signals", []),
                "tags": meta.get("tags", []),
                "added": meta["added"],
                "what": sections.get("What it is", ""),
                "why": sections.get("Why it's recommended", ""),
                "path": rel,
            }
        )
    entries.sort(key=lambda e: (list(CATEGORIES).index(e["category"]), e["id"]))
    return entries


def render_markdown(entries: list[dict]) -> str:
    total = len(entries)
    tiers = {t: sum(1 for e in entries if e["tier"] == t) for t in TIER_ORDER}
    with_prompt = sum(1 for e in entries if e["has_prompt"])

    lines = [
        "# Catalog",
        "",
        f"> **{total}** GPT-6 Astra entries \u00b7 {len(CATEGORIES)} categories \u00b7 "
        f"{tiers['featured']} featured, {tiers['notable']} notable, {tiers['community']} community "
        f"\u00b7 {with_prompt} ship a prompt.",
        "",
        "The discovery layer: prompts, demos, tools and guides from across the GPT-6 Astra "
        "ecosystem \u2014 most published first on X, many already indexed by other `awesome-*` "
        "lists \u2014 classified, credited and recommended. A prompt is optional here; for the "
        "reproducible, contract-checked recipes see [`prompts/`](prompts).",
        "",
        "**Generated by [`scripts/build_catalog.py`](scripts/build_catalog.py)** \u2014 edit the "
        "entries under [`catalog/entries/`](catalog/entries), never this file.",
        "",
        "Browse it as a page: [`site/index.html`](site/index.html) \u00b7 "
        "how tiers are decided: [`catalog/README.md`](catalog/README.md).",
        "",
        "| Tier | Meaning |",
        "| --- | --- |",
        "| \u2b50 featured | Editor-picked: high signal, attributable, clearly useful. |",
        "| \u2726 notable | Real traction or a clearly original contribution. |",
        "| \u00b7 community | Surfaced or submitted, not yet vetted. |",
        "",
        "---",
        "",
    ]

    for category, heading in CATEGORIES.items():
        rows = [e for e in entries if e["category"] == category]
        if not rows:
            continue
        rows.sort(key=lambda e: (TIER_ORDER.index(e["tier"]), e["id"]))
        lines += [f"## {heading}", ""]
        lines += ["| Tier | Entry | Kind | Prompt | Source | Stars |", "| --- | --- | --- | --- | --- | --- |"]
        for e in rows:
            stars = e["stars"] if e["stars"] is not None else "\u2014"
            prompt = "yes" if e["has_prompt"] else "no"
            link = f"[{e['title']}]({e['path']})"
            source = f"[{e['source_platform']}]({e['source_url']})"
            lines.append(
                f"| {TIER_BADGE[e['tier']]} | {link} | {KIND_LABEL[e['kind']]} "
                f"| {prompt} | {source} | {stars} |"
            )
        lines.append("")

    lines += ["---", "", f"_{total} entries. Source snapshots, star counts and links as recorded "
              f"on {max(e['added'] for e in entries)}._", ""]
    return "\n".join(lines)


