def write_or_check(path: Path, content: str, check: bool) -> bool:
    if check:
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        if current != content:
            print(f"\u2717 {path.relative_to(ROOT)} is stale \u2014 run: python3 scripts/build_catalog.py")
            return False
        return True
    if path.exists() and path.read_text(encoding="utf-8") == content:
        print(f"\u2713 {path.relative_to(ROOT)} already up to date")
        return True
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    print(f"\u2713 {path.relative_to(ROOT)} regenerated")
    return True


def main() -> int:
    check = "--check" in sys.argv
    if not check:
        result = subprocess.run([sys.executable, str(ROOT / "scripts" / "validate_catalog.py")])
        if result.returncode != 0:
            print("\u2717 catalog validation failed \u2014 fix errors before building")
            return 1

    entries = load()
    ok = write_or_check(CATALOG_MD, render_markdown(entries), check)
    ok = write_or_check(SITE, render_site(entries), check) and ok
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
